import { apiService } from './apiService';

/**
 * Reading the hypervisors.
 *
 * The overview answers with a list because more than one can be connected. A
 * single thin place knows that, so the page, the widget, the bookmark form and
 * the widget's own configuration do not each have to unwrap the same envelope
 * — and so the day a fifth caller appears it cannot unwrap it differently.
 */

/** A node as the overview reports it. Percentages, not fractions. */
export interface PxNode {
    name: string; status: string;
    cpu: number; mem: number; disk: number;
    threads: number; cores: number;
    /** Bytes in use, beside the percentage. */
    mem_used: number; mem_total: number;
    disk_used: number; disk_total: number;
    uptime: number; loadavg: string[] | null; guests: number;
}

export interface PxGuest {
    vmid: number; name: string; kind: 'lxc' | 'qemu'; node: string;
    running: boolean; cpu: number; mem: number; mem_total: number; uptime: number;
}

export interface PxStore {
    name: string; node: string; kind: string;
    used: number; total: number; percent: number; shared: boolean;
}

/** One hypervisor's worth of the answer. */
export interface PxHost {
    /** Generated by the server and stable; everything stored points at it. */
    id: string;
    name: string;
    /** Set when this host could not be read. The others still were. */
    error?: string;
    cluster: boolean;
    caps: { read: boolean; power: boolean };
    nodes: PxNode[];
    guests: PxGuest[];
    stores: PxStore[];
    /** Icons the operator chose, keyed "host|node|vmid". */
    icons?: Record<string, string>;
}

/**
 * Reads one hypervisor, or every connected one when none is named.
 *
 * Naming one is what a cluster's own page does on every poll: reading the
 * others costs a round trip to each of them for figures nobody is looking at.
 */
export async function loadProxmox(hostId?: string): Promise<PxHost[]> {
    const url = hostId ? `/api/proxmox/overview?host=${encodeURIComponent(hostId)}` : '/api/proxmox/overview';
    const out = await apiService.get<{ hosts?: PxHost[] }>(url);
    return out?.hosts ?? [];
}

/** The icon the operator chose for a machine, if any. */
export function chosenIcon(host: PxHost, node: string, vmid: number): string {
    return host.icons?.[`${host.id}|${node}|${vmid}`] || '';
}

/** Every machine across the hosts given, each carrying the host it is on. */
export function allGuests(hosts: PxHost[]): (PxGuest & { host: string; hostName: string })[] {
    const out: (PxGuest & { host: string; hostName: string })[] = [];
    for (const h of hosts) {
        for (const g of h.guests || []) out.push({ ...g, host: h.id, hostName: h.name });
    }
    return out;
}
